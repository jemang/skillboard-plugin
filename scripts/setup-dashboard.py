def hooks_rows(cfg):
    """(source, event, n) across settings.json + every enabled plugin's hooks/hooks.json."""
    rows = []
    def add(src, hooks_cfg):
        for event, groups in (hooks_cfg or {}).items():
            n = sum(len(g.get("hooks", [])) for g in groups)
            if n:
                rows.append((src, event, n))
    add("settings.json", cfg.get("hooks"))
    cache = os.path.join(H, ".claude", "plugins", "cache")
    for key, on in (cfg.get("enabledPlugins") or {}).items():
        if not on:
            continue
        name, _, mkt = key.partition("@")
        vers = glob.glob(os.path.join(cache, mkt, name, "*"))
        if not vers:
            continue
        root = newest_cache(vers)
        seen = set()
        # form 1: hooks declared in plugin.json (inline dict, or string path to a json file)
        try:
            with open(os.path.join(root, ".claude-plugin", "plugin.json"), encoding="utf-8") as f:
                hf = json.load(f).get("hooks")
            if isinstance(hf, dict):
                add(name, hf)
            elif isinstance(hf, str):
                fp = os.path.normpath(os.path.join(root, hf))
                seen.add(fp)
                with open(fp, encoding="utf-8") as f:
                    add(name, json.load(f).get("hooks"))
        except Exception:
            pass
        # form 2: auto-loaded hooks/hooks.json (skip if form 1 already pointed at it)
        fp = os.path.normpath(os.path.join(root, "hooks", "hooks.json"))
        if os.path.isfile(fp) and fp not in seen:
            try:
                with open(fp, encoding="utf-8") as f:
                    add(name, json.load(f).get("hooks"))
            except Exception:
                pass
    return sorted(rows, key=lambda r: (r[0] != "skillboard", r[0], -r[2]))


def maintenance():
    p = os.path.join(H, ".local", "state", "remember", "processed-claude-code")
    days = (time.time() - os.path.getmtime(p)) / 86400
    return days, max(0.0, 7 - days)


def brain():
    b = BRAIN
    def count(sub, rec=False):
        base = os.path.join(b, sub)
        if not os.path.isdir(base):
            return 0
        if not rec:
            return len([f for f in os.listdir(base) if f.endswith(".md")])
        return sum(len([f for f in fs if f.endswith(".md")]) for _, _, fs in os.walk(base))
    beliefs = 0
    m = safe(lambda: open(os.path.join(b, "Persona.md"), encoding="utf-8").read(), "")
    sec = re.search(r"## Top Beliefs\n(.*?)\n## ", m, re.S)
    if sec:
        beliefs = len(re.findall(r"^\d+\.", sec.group(1), re.M))
    return {"Notes": count("Notes"), "Journal": count("Journal"),
            "Projects": count("Projects", rec=True), "Patterns": count("Resources/patterns"),
            "Top beliefs": beliefs}


def plans():
    """Discover plan dirs under dev_root: any `.doc/` or `doc/plans/` (depth ≤4)."""
    prune = {".git", "node_modules", "vendor", ".venv", "venv", "storage", "dist", "build"}
    dirs = []
    depth0 = DEV.rstrip(os.sep).count(os.sep)
    for root, subdirs, _ in os.walk(DEV):
        if root.count(os.sep) - depth0 >= 6:
            subdirs[:] = []
            continue
        subdirs[:] = [d for d in subdirs if d not in prune]
        if os.path.basename(root) == ".doc" or root.endswith(os.path.join("doc", "plans")):
            dirs.append(root)
            subdirs[:] = []
    found = []
    for d in dirs:
        if not os.path.isdir(d):
            continue
        for f in os.listdir(d):
            if not f.endswith(".md"):
                continue
            p = os.path.join(d, f)
            status = ""
            head = safe(lambda: open(p, encoding="utf-8", errors="replace").read(2000), "")
            m = re.search(r"\*\*Status:?\*\*:?\s*(.+)", head)
            if m:
                status = m.group(1)[:90]
            found.append((os.path.getmtime(p), f, status, p))
    return [x[1:] for x in sorted(found, reverse=True)[:12]]


def bar(pct, hue="var(--blue)"):
    pct = max(2, min(100, int(pct)))
    return (f'<div class="meter"><div class="meter-fill" '
            f'style="width:{pct}%;background:{hue}"></div></div>')


def vslink(path, label):
    return f'<a class="mono flink" href="vscode://file{esc(path)}" title="open in VS Code">{esc(label)}</a>'


def plan_usage():
    """Claude plan usage %, same source as the /usage panel. OAuth token is
    read from Keychain in-process and used for one HTTPS call — it is never
    written to the page or disk. Returns [] when offline/no token (panel hides)."""
    import subprocess
    import urllib.request
    raw = subprocess.run(
        ["security", "find-generic-password", "-s", "Claude Code-credentials", "-w"],
        capture_output=True, text=True, timeout=5).stdout
    tok = json.loads(raw).get("claudeAiOauth", {}).get("accessToken", "")
    if not tok:
        return []
    req = urllib.request.Request(
        "https://api.anthropic.com/api/oauth/usage",
        headers={"Authorization": f"Bearer {tok}", "anthropic-beta": "oauth-2025-04-20"})
    with urllib.request.urlopen(req, timeout=5) as r:
        d = json.load(r)
    out = []
    for lim in d.get("limits") or []:
        if lim.get("percent") is None:
            continue
        label = {"session": "Session (5h)", "weekly_all": "Weekly · all models",
                 "weekly_opus": "Weekly · Opus", "weekly_fable": "Weekly · Fable",
                 "weekly_scoped": "Weekly · top models"}.get(
                    lim.get("kind"), lim.get("kind", "?"))
        reset = ""
        m = re.match(r"(\d+-\d+-\d+)T(\d+:\d+)", lim.get("resets_at") or "")
        if m:
            ts = time.mktime(time.strptime(f"{m.group(1)} {m.group(2)}", "%Y-%m-%d %H:%M"))
            ts -= time.timezone  # value is UTC; show local
            reset = "resets " + time.strftime("%a %H:%M", time.localtime(ts))
        out.append((label, int(lim.get("percent") or 0), lim.get("severity", "normal"), reset))
    return out


