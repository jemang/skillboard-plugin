def render_markdown(text):
    """Render a deliberately small, escaped Markdown subset for local previews."""
    out, paragraph, items, code = [], [], [], []
    in_code = False

    def flush_paragraph():
        if paragraph:
            out.append("<p>" + " ".join(esc(line.strip()) for line in paragraph) + "</p>")
            paragraph.clear()

    def flush_items():
        if items:
            out.append("<ul>" + "".join("<li>" + esc(item) + "</li>" for item in items) + "</ul>")
            items.clear()

    for line in text.splitlines():
        if line.startswith("```"):
            flush_paragraph()
            flush_items()
            if in_code:
                out.append("<pre><code>" + esc("\n".join(code)) + "</code></pre>")
                code.clear()
            in_code = not in_code
            continue
        if in_code:
            code.append(line)
            continue
        heading = re.match(r"^(#{1,3})\s+(.+)$", line)
        if heading:
            flush_paragraph()
            flush_items()
            level = len(heading.group(1))
            out.append(f"<h{level}>{esc(heading.group(2))}</h{level}>")
            continue
        item = re.match(r"^[-*]\s+(.+)$", line)
        if item:
            flush_paragraph()
            items.append(item.group(1))
            continue
        if not line.strip():
            flush_paragraph()
            flush_items()
            continue
        flush_items()
        paragraph.append(line)

    if in_code:
        out.append("<pre><code>" + esc("\n".join(code)) + "</code></pre>")
    flush_paragraph()
    flush_items()
    return "".join(out)


def file_preview(path, limit=12000):
    """Read a bounded local Markdown preview; unavailable files remain absent."""
    def read_file():
        with open(path, encoding="utf-8", errors="replace") as f:
            return f.read(limit + 1)

    text = safe(read_file, None)
    if text is None:
        return None
    truncated = len(text) > limit
    preview = text[:limit]
    return {"path": path, "folder": os.path.dirname(path), "html": render_markdown(preview),
            "truncated": truncated}


def capped_previews(groups, limit=6000):
    """Build preview payloads from ordered file groups with independent budgets."""
    previews, previewed = {}, set()
    for paths, budget in groups:
        remaining = budget
        for path in dict.fromkeys(paths):
            if path in previewed or remaining < 1200:
                continue
            preview = file_preview(path, limit=min(limit, remaining))
            if preview:
                previews[path] = preview
                previewed.add(path)
                remaining -= len(preview["html"])
    return previews


def plan_usage():
    """Claude plan usage %, same source as the /usage panel. OAuth token is
    read from Keychain in-process and used for one HTTPS call — it is never
    written to the page or disk. Returns [] when offline/no token (panel hides)."""
    import subprocess
    import urllib.request
    raw = subprocess.run(
        ["security", "find-generic-password", "-s", "Claude Code-credentials", "-w"],
        capture_output=True, text=True, timeout=5).stdout
    tok = json.loads(raw).get("claudeAiOauth", {}).get("accessToken", "")
    if not tok:
        return []
    req = urllib.request.Request(
        "https://api.anthropic.com/api/oauth/usage",
        headers={"Authorization": f"Bearer {tok}", "anthropic-beta": "oauth-2025-04-20"})
    with urllib.request.urlopen(req, timeout=5) as r:
        d = json.load(r)
    out = []
    for lim in d.get("limits") or []:
        if lim.get("percent") is None:
            continue
        label = {"session": "Session (5h)", "weekly_all": "Weekly · all models",
                 "weekly_opus": "Weekly · Opus", "weekly_fable": "Weekly · Fable",
                 "weekly_scoped": "Weekly · top models"}.get(
                    lim.get("kind"), lim.get("kind", "?"))
        reset = ""
        m = re.match(r"(\d+-\d+-\d+)T(\d+:\d+)", lim.get("resets_at") or "")
        if m:
            ts = time.mktime(time.strptime(f"{m.group(1)} {m.group(2)}", "%Y-%m-%d %H:%M"))
            ts -= time.timezone  # value is UTC; show local
            reset = "resets " + time.strftime("%a %H:%M", time.localtime(ts))
        out.append((label, int(lim.get("percent") or 0), lim.get("severity", "normal"), reset))
    return out


