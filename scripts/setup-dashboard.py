def newest_cache(paths, up=0):
    """Pick highest plugin version numerically; the version dir sits `up` levels above each path."""
    return max(paths, key=lambda p: [int(x) for x in re.findall(r"\d+", p.split(os.sep)[-1 - up])] or [-1])


def esc(s):
    return html.escape(str(s))


def safe(fn, default):
    try:
        return fn()
    except Exception:
        return default


def mem_stats():
    db = os.path.join(H, ".claude", "memory-index.db")
    con = sqlite3.connect(db)
    by = dict(con.execute("SELECT source, count(*) FROM mem GROUP BY source"))
    total = sum(by.values())
    con.close()
    age = time.time() - os.path.getmtime(db)
    return by, total, age


def mem_list():
    """Every indexed memory: (source, title, path) sorted by source then title."""
    db = os.path.join(H, ".claude", "memory-index.db")
    con = sqlite3.connect(db)
    rows = con.execute("SELECT source, title, path FROM mem ORDER BY source, title").fetchall()
    con.close()
    return rows


def mem_loc(source, path):
    """Compact origin label so same-named files across projects stay distinct."""
    if source == "auto-memory":
        m = re.search(r"/projects/([^/]+)/memory/", path)
        slug = m.group(1) if m else ""
        return re.sub("^" + re.escape(DEV.replace(os.sep, "-")) + "-?", "", slug) or "global"
    if source == "brain":
        rel = os.path.relpath(os.path.dirname(path), BRAIN)
        return "" if rel == "." else rel
    if source == "repo":
        return os.path.relpath(path, DEV)
    return ""


def mem_origin(source, path):
    """Compact filter key: repo top-folder / brain section / codex / auto-memory project slug."""
    if source == "brain":
        rel = os.path.relpath(os.path.dirname(path), BRAIN)
        return "brain" if rel == "." else "brain/" + rel.split(os.sep)[0]
    if source == "codex":
        return "codex"
    if source == "repo":
        return os.path.relpath(path, DEV).split(os.sep)[0]
    return mem_loc(source, path) or "global"


def _scan_skills(root):
    out = []
    if not os.path.isdir(root):
        return out
    for d in sorted(os.listdir(root)):
        p = os.path.join(root, d, "SKILL.md")
        if not os.path.isfile(p):
            continue
        desc = ""
        with open(p, encoding="utf-8", errors="replace") as f:
            txt = f.read(4000)
        m = re.search(r"^description:\s*>?-?\s*\"?(.+?)\"?$", txt, re.M)
        if m:
            desc = m.group(1)
        dates = re.findall(r"[Rr]e(?:searched|-verified)\s+(\d{4}-\d{2}-\d{2})", txt)
        stamp = max(dates) if dates else ""
        out.append((d, desc[:110] + ("…" if len(desc) > 110 else ""), p, stamp))
    return out


def skill_age_days(stamp):
    try:
        return int((time.time() - time.mktime(time.strptime(stamp, "%Y-%m-%d"))) // 86400)
    except (ValueError, TypeError, OverflowError):
        return None


